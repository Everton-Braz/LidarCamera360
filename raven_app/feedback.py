"""Bug reporting, user feedback collection, and diagnostic packaging."""
import json
import os
import platform
import sys
import urllib.parse
import urllib.request
import webbrowser
import zipfile
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

from raven_app import __version__
from raven_app.branding import APP_NAME, REPOSITORY_NAME
from raven_app.config import get_config_dir, load_config
from raven_app.telemetry import get_system_telemetry_payload

DEFAULT_REPO = f"Everton-Braz/{REPOSITORY_NAME}"


def gather_diagnostics() -> Dict[str, Any]:
    """Compiles full non-sensitive diagnostic info for bug reporting."""
    diagnostics = get_system_telemetry_payload()
    
    # Gather engine statuses
    try:
        from raven_app.cli import engine
        eng_path = engine()
        diagnostics["native_engine_exists"] = eng_path.is_file()
        diagnostics["native_engine_path"] = str(eng_path)
    except Exception as exc:
        diagnostics["native_engine_error"] = str(exc)

    try:
        from raven_app.config import get_spirula_bin, validate_tool
        sp = get_spirula_bin()
        ok_sp, ver_sp = validate_tool("spirula", str(sp))
        diagnostics["spirula_path"] = str(sp)
        diagnostics["spirula_ready"] = ok_sp
        diagnostics["spirula_version"] = ver_sp
    except Exception as exc:
        diagnostics["spirula_error"] = str(exc)

    # Check for recent logs
    log_dir = get_config_dir() / "logs"
    recent_logs = []
    if log_dir.is_dir():
        log_files = sorted(log_dir.glob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True)
        for lf in log_files[:3]:
            try:
                lines = lf.read_text(encoding="utf-8", errors="replace").splitlines()
                recent_logs.append({
                    "file": lf.name,
                    "tail": lines[-40:] if len(lines) > 40 else lines
                })
            except Exception:
                pass
    diagnostics["recent_logs"] = recent_logs
    return diagnostics


def format_markdown_report(report: Dict[str, Any]) -> str:
    """Formats a feedback report into structured GitHub Flavored Markdown."""
    category = report.get("category", "bug").upper()
    title = report.get("title", "No Title")
    desc = report.get("description", "")
    steps = report.get("steps", "")
    contact = report.get("contact", "")
    diag = report.get("diagnostics", {})

    md = [
        f"## [{category}] {title}",
        "",
        "### Description",
        desc or "_No description provided._",
        "",
    ]

    if steps:
        md.extend([
            "### Steps to Reproduce",
            steps,
            "",
        ])

    if contact:
        md.extend([
            "### Contact / Reporter",
            contact,
            "",
        ])

    if diag:
        md.extend([
            "### System Diagnostics",
            "```json",
            json.dumps(diag, indent=2, ensure_ascii=False),
            "```",
            "",
        ])

    md.append(f"_Generated by {APP_NAME} v{__version__} at {datetime.now().isoformat()}_")
    return "\n".join(md)


def build_github_issue_url(report: Dict[str, Any], repo: Optional[str] = None) -> str:
    """Generates a pre-filled GitHub new issue URL."""
    cfg = load_config()
    target_repo = repo or cfg.get("feedback_repo") or DEFAULT_REPO
    
    category = report.get("category", "bug").lower()
    prefix = "[Bug]: " if category == "bug" else ("[Feature]: " if category == "feature" else "[Feedback]: ")
    title = prefix + report.get("title", "").strip()
    body = format_markdown_report(report)

    # URL encode parameters
    params = urllib.parse.urlencode({
        "title": title,
        "body": body,
    })
    return f"https://github.com/{target_repo}/issues/new?{params}"


def open_github_issue_in_browser(report: Dict[str, Any], repo: Optional[str] = None) -> bool:
    """Opens the browser directly with the pre-filled issue URL."""
    try:
        url = build_github_issue_url(report, repo=repo)
        return webbrowser.open(url)
    except Exception as exc:
        print(f"[!] Failed to open browser: {exc}", file=sys.stderr)
        return False


def send_feedback_webhook(
    report: Dict[str, Any],
    webhook_url: Optional[str] = None,
    timeout: int = 10
) -> Dict[str, Any]:
    """Posts the feedback report to a configured Discord/Telegram/HTTP webhook."""
    cfg = load_config()
    url = webhook_url or cfg.get("feedback_webhook")
    if not url:
        return {"status": "noop", "message": "No feedback webhook configured."}

    # Check if Discord webhook
    is_discord = "discord.com/api/webhooks" in url or "discordapp.com/api/webhooks" in url
    if is_discord:
        title = f"[{report.get('category', 'feedback').upper()}] {report.get('title', 'Feedback')}"
        desc = report.get("description", "")[:1900]
        payload = {
            "content": f"**{title}**\n{desc}\n_Version: {APP_NAME} v{__version__}_"
        }
    else:
        payload = {
            "app": APP_NAME,
            "version": __version__,
            "report": report,
            "timestamp": datetime.now().isoformat()
        }

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json", "User-Agent": f"{APP_NAME}-Feedback/{__version__}"},
        method="POST"
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return {"status": "success", "code": resp.status}
    except Exception as exc:
        return {"status": "error", "error": str(exc)}


def export_feedback_bundle(report: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """Exports the report and attached diagnostics into a convenient zip archive."""
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    default_path = get_config_dir() / f"feedback_bundle_{timestamp}.zip"
    out_zip = Path(output_path or default_path)
    out_zip.parent.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(out_zip, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("report.json", json.dumps(report, indent=2, ensure_ascii=False))
        zf.writestr("report.md", format_markdown_report(report))
        if "diagnostics" in report:
            zf.writestr("diagnostics.json", json.dumps(report["diagnostics"], indent=2, ensure_ascii=False))

    return out_zip
